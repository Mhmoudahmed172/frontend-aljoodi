const fs = require('node:fs')
const assert = require('node:assert/strict')
const postcss = require('postcss')
const hero = fs.readFileSync('src/features/landing/components/HeroSection.tsx', 'utf8')
assert(hero.includes('unoptimized'))
assert(hero.includes('width={1448}'))
assert(hero.includes('height={1086}'))
assert(!hero.includes('CatalogMetrics'))
assert(!hero.includes('heroPhotoPlane'))
const teachers = fs.readFileSync('src/features/landing/components/TeachersSection.tsx', 'utf8')
assert(teachers.includes('portraits.map'))
assert(!teachers.includes('TeacherCard'))
assert(!teachers.includes('useTeachers'))
const subjects = fs.readFileSync('src/features/landing/components/SubjectsSection.tsx', 'utf8')
assert(subjects.includes('aria-pressed'))
assert(subjects.includes('editorial'))
assert(!subjects.includes('next/image'))
assert(!subjects.includes('demoImages'))
const css = postcss.parse(fs.readFileSync('src/components/brand/homepage.css', 'utf8'))
let columns = false,
  imageFull = false
css.walkRules((rule) => {
  if (rule.selector === '.aj-home .aj-heroGrid') columns ||= rule.nodes.some((n) => n.prop === 'grid-template-columns' && n.value.includes('1.22fr'))
  if (rule.selector === '.aj-home .aj-heroComposite') imageFull = rule.nodes.some((n) => n.prop === 'height' && n.value === 'auto')
})
assert(columns && imageFull)
const publicCss = postcss.parse(fs.readFileSync('src/components/brand/public.css', 'utf8'))
publicCss.walkRules((r) => {
  if (r.selector === '.aj-heroComposite') r.walkDecls((d) => assert(!d.prop.includes('mask'), 'No feathering on composite'))
})
const html = fs.readFileSync('.next/server/app/index.html', 'utf8')
assert(html.includes('aj-homeFaculty'))
for (let i = 1; i <= 4; i++) assert(html.includes(`home-teacher-${i}.jpg`))
assert(!html.includes('aj-metric'))
assert(!html.includes('aj-teacherFeatured'))
assert(!html.includes('aj-homeProduct'))
assert(!html.includes('aj-learningJourney'))
assert(!fs.existsSync('src/components/brand/LearningJourney.tsx'))
assert(!fs.existsSync('src/features/landing/components/HowSection.tsx'))
const order = ['aj-hero', 'aj-homeTeachers', 'aj-homeCourses', 'aj-summit'].map((c) => html.indexOf(c))
assert(order.every((n) => n >= 0))
assert(order.every((n, i) => i === 0 || n > order[i - 1]))
console.log(
  'Homepage checks passed: full source image, no edge effects/counters, four original portraits, direct filtered course grid, removed learning demo and retained section order.',
)
